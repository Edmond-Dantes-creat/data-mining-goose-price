def read(path: str) -> str:
    if not os.path.exists(path):
        return f"> （缺少文件：{os.path.basename(path)}）\n"
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def demote(md: str, levels: int = 2) -> str:
    """把 Markdown 标题整体降级，避免嵌入后与报告主标题同级。"""
    return re.sub(r"^(#{1,4}) ", lambda m: "#" * (len(m.group(1)) + levels) + " ",
                  md, flags=re.M)


def shots_block(section: str) -> str:
    """扫描 screenshots/，生成附录对应小节要插入的图片引用；没图就保留占位文字。

    命名约定：文件名以 11.5 或 git 开头 → 归入「11.5 Git 提交记录」，
    其余图片 → 归入「11.4 运行截图」。这样重跑本脚本也不会把截图覆盖掉。
    """
    placeholder = {
        "11.4": "（此处插入 PyCharm 运行截图：终端输出 + 代码窗口）",
        "11.5": "（此处插入 Git 提交记录截图）",
    }[section]
    caption = {"11.4": "PyCharm 运行截图", "11.5": "Git 提交记录截图"}[section]
    base_no = {"11.4": 9, "11.5": 10}[section]

    if not os.path.isdir(SHOT_DIR):
        return placeholder

    files = sorted(
        (f for f in os.listdir(SHOT_DIR) if f.lower().endswith(IMG_EXTS)),
        key=str.lower,
    )
    want_git = section == "11.5"
    picked = [
        f for f in files
        if (f.lower().startswith("11.5") or f.lower().startswith("git")) == want_git
    ]
    if not picked:
        return placeholder

    total = len(picked)
    lines: list[str] = []
    for i, name in enumerate(picked, 1):
        no = f"{base_no}-{i}" if total > 1 else str(base_no)
        lines.append(f"![图 {no}　{caption}](screenshots/{name})")
        lines.append("")
    return "\n".join(lines).rstrip()


